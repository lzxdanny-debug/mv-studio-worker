#!/usr/bin/env node
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

function resolveGitSha() {
  const fromEnv =
    process.env.CF_PAGES_COMMIT_SHA ||
    process.env.GITHUB_SHA ||
    process.env.CI_COMMIT_SHA;
  if (fromEnv) return fromEnv.slice(0, 7);
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd: root,
      encoding: 'utf8',
    }).trim();
  } catch {
    return 'unknown';
  }
}

const info = {
  service: pkg.name,
  version: pkg.version,
  gitSha: resolveGitSha(),
  buildTime: new Date().toISOString(),
};

const outDir = join(root, 'src/generated');
mkdirSync(outDir, { recursive: true });

const ts = `/** Auto-generated by scripts/write-build-info.mjs — do not edit manually */
export const BUILD_INFO = ${JSON.stringify(info, null, 2)} as const;
export type BuildInfo = typeof BUILD_INFO;
`;

writeFileSync(join(outDir, 'build-info.ts'), ts);
console.log(`[build-info] ${info.service} v${info.version} (${info.gitSha})`);
